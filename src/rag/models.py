"""
MedFront RAG Data Models.
Defines schemas for document chunks, metadata, queries, and search results.
"""

from typing import Any

from pydantic import BaseModel, Field


class DocumentMetadata(BaseModel):
    """Metadata attached to each indexed document chunk."""
    source: str = Field(..., description="Originating document or system")
    category: str = Field(..., description="Category: clinic_policy, insurance, procedure_prep, soap_note, call_transcript, lab_result")
    patient_id: str | None = Field(default=None, description="Partition filter key for HIPAA patient isolation")
    patient_name: str | None = Field(default=None, description="Patient full name if applicable")
    record_type: str | None = Field(default=None, description="Detailed record type")
    author: str | None = Field(default="system", description="Author or recording persona")
    access_level: str = Field(default="administrative", description="'administrative' or 'clinical'")
    timestamp: str | None = Field(default=None, description="ISO timestamp of encounter or policy date")

    def to_dict(self) -> dict[str, Any]:
        return self.model_dump()


class DocumentChunk(BaseModel):
    """A granular snippet of knowledge indexed with an embedding and metadata."""
    id: str = Field(..., description="Unique chunk identifier")
    text: str = Field(..., description="Text content used for matching and LLM context")
    metadata: DocumentMetadata = Field(..., description="Filterable metadata")
    embedding: list[float] | None = Field(default=None, description="Dense vector representation")

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "text": self.text,
            "metadata": self.metadata.to_dict(),
            "embedding": self.embedding,
        }


class SearchResult(BaseModel):
    """A single retrieved chunk with its similarity score and source citation."""
    chunk_id: str
    text: str
    score: float = Field(..., description="Relevance similarity score (higher is more relevant)")
    metadata: DocumentMetadata

    @property
    def citation(self) -> str:
        source_name = self.metadata.source
        if self.metadata.patient_id:
            return f"{source_name} [Patient: {self.metadata.patient_id}, Type: {self.metadata.record_type or self.metadata.category}]"
        return f"{source_name} [{self.metadata.category}]"


class RAGQuery(BaseModel):
    """Standard search query request."""
    query: str = Field(..., description="Natural language search query")
    patient_id: str | None = Field(default=None, description="Mandatory for patient-scoped records; None for clinic knowledge")
    category: str | None = Field(default=None, description="Optional category filter")
    access_level: str | None = Field(default=None, description="Filter for receptionist vs doctor")
    top_k: int = Field(default=3, ge=1, le=10, description="Number of results to retrieve")


class RAGAnswer(BaseModel):
    """Final answer generated by grounding an LLM with retrieved chunks."""
    query: str
    answer: str
    citations: list[str] = Field(default_factory=list)
    results: list[SearchResult] = Field(default_factory=list)
