"""
Data contracts and interfaces exchanged between Brain, RAG, Tools, and TTS.
"""

from dataclasses import dataclass, field
from typing import Optional, Dict, Any, List
from src.brain.taxonomy import IntentCategory, ToolName


@dataclass
class IntentDecision:
    """
    Structured decision payload generated by the IntentRouter LLM.
    """
    intent: IntentCategory
    confidence: float = 1.0
    rag_query: Optional[str] = None
    target_index: Optional[str] = None  # "clinic_faq" or "patient_records"
    tool_name: Optional[ToolName] = None
    tool_parameters: Dict[str, Any] = field(default_factory=dict)
    reasoning: str = ""


@dataclass
class RAGRequest:
    """
    Contract for sending search queries to the RAG layer.
    """
    query_text: str
    index_target: str = "clinic_faq"  # "clinic_faq" or "patient_records"
    patient_id: Optional[str] = None
    top_k: int = 3


@dataclass
class RAGResponse:
    """
    Contract for data returned from the RAG layer to the Brain.
    """
    success: bool
    retrieved_chunks: List[str] = field(default_factory=list)
    sources: List[str] = field(default_factory=list)
    error_message: Optional[str] = None


@dataclass
class ToolCallRequest:
    """
    Contract for requesting backend tool execution.
    """
    tool_name: ToolName
    parameters: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ToolCallResult:
    """
    Contract returned by backend tools after execution.
    """
    success: bool
    output_data: Dict[str, Any] = field(default_factory=dict)
    user_message: str = ""
    error_message: Optional[str] = None


@dataclass
class PatientInfoPayload:
    """
    Structured patient metadata harvested for RAG ingestion.
    """
    full_name: Optional[str] = None
    dob: Optional[str] = None
    reason_for_visit: Optional[str] = None
    summary_notes: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "full_name": self.full_name,
            "dob": self.dob,
            "reason_for_visit": self.reason_for_visit,
            "summary_notes": self.summary_notes,
        }


@dataclass
class BrainOutput:
    """
    The unified result container produced by the Brain Orchestrator on every turn.
    """
    speech_text: str  # For Text-to-Speech (TTS)
    intent_detected: IntentCategory
    rag_used: bool = False
    tool_used: Optional[str] = None
    patient_ingestion_payload: Optional[Dict[str, Any]] = None
